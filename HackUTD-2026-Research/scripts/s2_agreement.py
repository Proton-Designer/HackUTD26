"""S2: per-field agreement between two independent pilot taggers.

In:  data/tagged/pilot/tagger_a.jsonl, tagger_b.jsonl (or paths given as argv[1], argv[2])
Out: data/tagged/pilot/agreement.md (+ agreement.csv)

Rules:
- Categorical fields: exact agreement % and Cohen's kappa. Pass = exact >= 70%.
- 1-5 ratings and n_user_flows: exact % and within-1 %. Pass = within-1 >= 70% (ordinal scale) AND exact reported.
- Free-text fields (technical_centerpiece, wow_moment): agreement only on none_visible vs something.
- sponsor_fit: entries matched by normalized track name; fields compared over tracks both taggers listed;
  track-listing agreement reported separately.
"""
import json, sys, re, csv, collections, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[1]
PD = ROOT / 'data/tagged/pilot'
fa = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else PD / 'tagger_a.jsonl'
fb = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else PD / 'tagger_b.jsonl'
out_md = pathlib.Path(sys.argv[3]) if len(sys.argv) > 3 else PD / 'agreement.md'
A = {json.loads(l)['blind_id']: json.loads(l) for l in open(fa)}
B = {json.loads(l)['blind_id']: json.loads(l) for l in open(fb)}
ids = [i for i in A if i in B]

def v(rec, f):
    x = rec.get(f)
    return x.get('v') if isinstance(x, dict) else x

def kappa(pairs):
    n = len(pairs)
    if not n: return None
    po = sum(a == b for a, b in pairs) / n
    ca, cb = collections.Counter(a for a, _ in pairs), collections.Counter(b for _, b in pairs)
    pe = sum(ca[k] * cb[k] for k in set(ca) | set(cb)) / (n * n)
    return None if pe == 1 else (po - pe) / (1 - pe)

def num(x):
    try: return float(x)
    except Exception: return None

res = []
def add(field, pairs, kind):
    pairs = [(json.dumps(a), json.dumps(b)) if kind == 'cat' else (a, b) for a, b in pairs]
    n = len(pairs)
    if n == 0: res.append(dict(field=field, kind=kind, n=0)); return
    exact = sum(a == b for a, b in pairs) / n
    row = dict(field=field, kind=kind, n=n, exact=round(exact * 100), kappa='', within1='', passes='')
    if kind == 'cat':
        k = kappa(pairs); row['kappa'] = '' if k is None else round(k, 2); row['passes'] = exact >= 0.7
    else:
        nums = [(num(a), num(b)) for a, b in pairs]
        both = [(a, b) for a, b in nums if a is not None and b is not None]
        w1 = sum(abs(a - b) <= 1 for a, b in both) / len(both) if both else 0
        unk_agree = sum((num(a) is None) == (num(b) is None) for a, b in pairs) / n
        row['within1'] = round(w1 * 100); row['passes'] = w1 >= 0.7 and unk_agree >= 0.7
        row['kappa'] = f'numeric n={len(both)}; unknown-status agree {round(unk_agree*100)}%'
    res.append(row)

for f in ['pattern', 'named_user', 'cost_of_problem_stated', 'ai_role', 'live_data', 'mocked_parts_disclosed',
          'novelty_source', 'centerpiece_visible']:
    add(f, [(v(A[i], f), v(B[i], f)) for i in ids], 'cat')
add('n_user_flows', [(v(A[i], 'n_user_flows'), v(B[i], 'n_user_flows')) for i in ids], 'ord')
for f in ['technical_centerpiece', 'wow_moment']:
    add(f + ' (none_visible vs some)', [(v(A[i], f) == 'none_visible', v(B[i], f) == 'none_visible') for i in ids], 'cat')
for d in ['innovation', 'technical_complexity', 'completeness', 'design', 'impact', 'presentation']:
    add('rating.' + d, [((A[i].get('ratings') or {}).get(d, {}).get('v'), (B[i].get('ratings') or {}).get(d, {}).get('v')) for i in ids], 'ord')

norm = lambda s: re.sub(r'[^a-z0-9]', '', (s or '').lower())[:12]
track_pairs, tl_agree = collections.defaultdict(list), []
for i in ids:
    ta = {norm(t.get('track')): t for t in A[i].get('sponsor_fit') or []}
    tb = {norm(t.get('track')): t for t in B[i].get('sponsor_fit') or []}
    tl_agree.append((sorted(ta), sorted(tb)))
    for k in set(ta) & set(tb):
        for f in ['sponsor_features_used', 'sponsor_removable', 'prompt_literalness', 'prompt_words_in_title', 'problem_owner']:
            track_pairs[f].append((v(ta[k], f), v(tb[k], f)))
add('sponsor_fit: same track list', [(a, b) for a, b in tl_agree], 'cat')
for f in ['sponsor_removable', 'prompt_literalness', 'prompt_words_in_title', 'problem_owner']:
    add('sponsor_fit.' + f, track_pairs[f], 'cat')
add('sponsor_fit.sponsor_features_used', track_pairs['sponsor_features_used'], 'ord')

with open(out_md.with_suffix('.csv'), 'w', newline='') as fo:
    w = csv.DictWriter(fo, fieldnames=['field', 'kind', 'n', 'exact', 'within1', 'kappa', 'passes']); w.writeheader()
    for r in res: w.writerow({k: r.get(k, '') for k in w.fieldnames})
L = [f'# Pilot agreement ({fa.name} vs {fb.name})', '', f'Projects compared: {len(ids)}. Generated by `scripts/s2_agreement.py`.',
     'Pass rule: categorical exact >= 70%; ordinal (ratings, counts) within-1 >= 70% and unknown-status agreement >= 70%.', '',
     '| field | kind | n | exact % | within-1 % | kappa / note | passes |', '|---|---|---|---|---|---|---|']
for r in res:
    L.append(f"| {r['field']} | {r['kind']} | {r['n']} | {r.get('exact','')} | {r.get('within1','')} | {r.get('kappa','')} | {r.get('passes','')} |")
fails = [r['field'] for r in res if r.get('passes') is False]
L += ['', f'**Below threshold:** {", ".join(fails) if fails else "none"}']
out_md.write_text('\n'.join(L) + '\n'); print('\n'.join(L))
