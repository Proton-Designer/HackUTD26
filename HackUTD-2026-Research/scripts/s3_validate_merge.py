"""S3: validate tag+rate shard outputs against the schema and merge.
In:  data/tagged/content/shard_*_in.jsonl + matching shard_*_out.jsonl
Out: data/tagged/content_all.jsonl (valid rows; adds _shard, _model), data/tagged/validation_report.md,
     data/tagged/content/retag_needed.csv (blind_id, shard, problems)
"""
import json, csv, pathlib, collections
ROOT = pathlib.Path(__file__).resolve().parents[1]
D = ROOT / 'data/tagged/content'
E = {
 'pattern': {'docs_to_action', 'sensor_to_alert_or_action', 'vision_to_assist', 'voice_to_action', 'data_to_decision',
             'risk_detect_and_respond', 'translate_between_people_or_systems', 'workflow_automation_agent',
             'realtime_coordination', 'education_feedback', 'game_or_social', 'spatial_ar', 'devtool', 'other'},
 'named_user': {True, False},
 'cost_of_problem_stated': {'none', 'asserted', 'cited_stat', 'user_quote_or_interview', 'measured_by_team'},
 'ai_role': {'none', 'single_call_wrapper', 'rag_or_chat', 'agentic_multistep', 'multimodal_pipeline',
             'custom_or_finetuned_model', 'on_device'},
 'live_data': {'yes', 'no', 'unknown'}, 'mocked_parts_disclosed': {'yes', 'no', 'unknown'},
 'novelty_source': {'new_user_group', 'new_interaction', 'new_data_or_context', 'technical_method', 'combination',
                    'execution_of_familiar_idea'},
 'centerpiece_visible': {'in_demo_output', 'shown_via_diagram_or_logs', 'described_only', 'none'},
}
SF = {'sponsor_removable': {'yes', 'no', 'unknown'}, 'prompt_literalness': {0, 1, 2, 'na'},
      'prompt_words_in_title': {0, 1, 2, 'na'},
      'problem_owner': {'consumer', 'sponsor_internal_or_b2b', 'sponsor_customers', 'unknown'}}
DIMS = ['innovation', 'technical_complexity', 'completeness', 'design', 'impact', 'presentation']

def v(x): return x.get('v') if isinstance(x, dict) else x
def check(r):
    p = []
    for f, ok in E.items():
        if v(r.get(f)) not in ok: p.append(f'{f}={v(r.get(f))!r}')
        elif isinstance(r.get(f), dict) and v(r[f]) not in ('unknown',) and not r[f].get('ev') and f != 'named_user':
            p.append(f'{f}: no ev')
    n = v(r.get('n_user_flows'))
    if not (n == 'unknown' or (isinstance(n, int) and 0 <= n <= 20)): p.append(f'n_user_flows={n!r}')
    for f in ('technical_centerpiece', 'wow_moment'):
        if not isinstance(v(r.get(f)), str) or not v(r.get(f)): p.append(f'{f} missing')
    if not isinstance(r.get('one_sentence'), str): p.append('one_sentence missing')
    if not isinstance(r.get('sponsor_fit'), list): p.append('sponsor_fit not list')
    for t in r.get('sponsor_fit') or []:
        for f, ok in SF.items():
            if v(t.get(f)) not in ok: p.append(f'sponsor_fit.{f}={v(t.get(f))!r}')
        su = v(t.get('sponsor_features_used'))
        if not (su == 'unknown' or isinstance(su, int)): p.append(f'sponsor_features_used={su!r}')
    for d in DIMS:
        x = v((r.get('ratings') or {}).get(d))
        if not (x in (1, 2, 3, 4, 5) or (d == 'design' and x == 'unknown')): p.append(f'rating.{d}={x!r}')
    return p

shards = list(csv.DictReader(open(D / 'shards.csv')))
good, retag, stat = [], [], []
for s in shards:
    ins = [json.loads(l)['blind_id'] for l in open(D / f"{s['shard']}_in.jsonl")]
    of = D / f"{s['shard']}_out.jsonl"
    outs = {}
    if of.exists():
        for l in open(of):
            try: r = json.loads(l); outs[r['blind_id']] = r
            except Exception: pass
    nok = 0
    for b in ins:
        r = outs.get(b)
        if r is None: retag.append(dict(blind_id=b, shard=s['shard'], problems='missing')); continue
        p = check(r)
        if p: retag.append(dict(blind_id=b, shard=s['shard'], problems='; '.join(p[:6]))); continue
        r['_shard'], r['_model'] = s['shard'], s['model']; good.append(r); nok += 1
    stat.append(dict(shard=s['shard'], model=s['model'], n_in=len(ins), n_out=len(outs), valid=nok, exists=of.exists()))

with open(ROOT / 'data/tagged/content_all.jsonl', 'w') as f:
    for r in good: f.write(json.dumps(r, ensure_ascii=False) + '\n')
with open(D / 'retag_needed.csv', 'w', newline='') as f:
    w = csv.DictWriter(f, fieldnames=['blind_id', 'shard', 'problems']); w.writeheader(); w.writerows(retag)
pc = collections.Counter(x.split('=')[0].split(':')[0] for r in retag for x in r['problems'].split('; '))
L = ['# S3 validation report', '', 'Generated by `scripts/s3_validate_merge.py`.', '',
     f"Valid rows: {len(good)} of {sum(int(s['n']) for s in shards)}; needing re-tag: {len(retag)}", '',
     '| shard | model | in | out | valid | file exists |', '|---|---|---|---|---|---|',
     *[f"| {s['shard']} | {s['model']} | {s['n_in']} | {s['n_out']} | {s['valid']} | {s['exists']} |" for s in stat], '',
     '## Problem types', *[f'- {k}: {n}' for k, n in pc.most_common()]]
(ROOT / 'data/tagged/validation_report.md').write_text('\n'.join(L) + '\n')
print('\n'.join(L[:5]))
