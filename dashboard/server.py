def find_token():
    for var in ("GITHUB_TOKEN", "GH_TOKEN"):
        t = os.environ.get(var, "").strip()
        if t:
            return t
    try:
        out = subprocess.run(["gh", "auth", "token"], capture_output=True, text=True, timeout=8)
        if out.returncode == 0 and out.stdout.strip():
            return out.stdout.strip().splitlines()[0].strip()
    except Exception:
        pass
    return None


def lan_ip():
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("10.255.255.255", 1))  # no packet is actually sent
        ip = s.getsockname()[0]
        s.close()
        return ip
    except Exception:
        try:
            return socket.gethostbyname(socket.gethostname())
        except Exception:
            return None


# --------------------------------------------------------------------------- message text parsing
SIG_RE = re.compile(r"_from: (P4a|P4b|P1|P2|P3|P4) ")
TITLE_RE = re.compile(r"^\s*\[\s*(?:📢\s*)?([A-Za-z0-9]+)\s*(?:→|->|-->|to)\s*([A-Za-z0-9]+)\s*\]\s*(.*)$", re.S)
FOOTER_RE = re.compile(r"\n*(?:---\s*\n)?_?Generated by .*$", re.S)
SIGLINE_RE = re.compile(r"\n*(?:---\s*\n)?_from: [^\n]*_\s*$")


def clean_body(body):
    b = (body or "").replace("\r", "").strip()
    for _ in range(4):
        nb = SIGLINE_RE.sub("", FOOTER_RE.sub("", b)).strip()
        if nb == b:
            break
        b = nb
    return b


def norm_token(tok):
    t = (tok or "").strip()
    if t.upper() == "ALL":
        return "ALL"
    return t[:1].upper() + t[1:].lower() if t else t  # P4A->P4a, p4->P4


