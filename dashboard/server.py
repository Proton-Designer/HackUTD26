class DemoCollector:
    def __init__(self, core):
        self.core = core
        self.rnd = random.Random()
        self.cid = 4000000000
        self.next_thread = 14
        self.bag = []
        self.cycle = 0
        self.pending = []      # (due_epoch, fn)
        self.open_threads = {}  # number -> (tpl, thread)
        self.next_msg_at = 0
        self.msgs, self.threads = [], {}
        self._seed()

    # ---- messages
    def _tpl(self):
        if not self.bag:
            self.bag = list(range(len(DEMO_TEMPLATES)))
            self.rnd.shuffle(self.bag)
            self.cycle += 1
        tpl = DEMO_TEMPLATES[self.bag.pop()]
        if self.cycle > 1:
            tpl = (tpl[0], tpl[1], tpl[2] + " (rev %d)" % self.cycle) + tuple(tpl[3:])
        return tpl

    def _url(self, n, cid=None):
        base = "https://github.com/%s/issues/%d" % (self.core.repo, n)
        return base + ("#issuecomment-%d" % cid if cid else "")

    def _new_thread(self, ts):
        tpl = self._tpl()
        frm, to, subj, body = tpl[0], tpl[1], tpl[2], tpl[3]
        n = self.next_thread
        self.next_thread += 1
        thread = {"number": n, "title": subj, "state": "open", "from": frm, "to": [to], "replies": 0,
                  "updated_at": iso(ts), "url": self._url(n)}
        self.threads[n] = thread
        self.msgs.append({"id": "i%d" % n, "thread": n, "kind": "thread", "from": frm,
                          "to": self.core.expand([to], frm), "title": subj, "body": body,
                          "created_at": iso(ts), "url": thread["url"]})
        self.open_threads[n] = (tpl, thread)
        return n

    def _reply(self, n, ts, close=False):
        if n not in self.open_threads:
            return
        tpl, th = self.open_threads[n]
        recips = self.core.expand(th["to"])
        if not close:
            frm = self.rnd.choice(recips)
            text = tpl[4]
        else:
            frm = self.rnd.choice(recips)
            text = tpl[5] or "Done on my side."
        to = [p for p in recips + [th["from"]] if p != frm]
        self.cid += self.rnd.randint(1000, 90000)
        self.msgs.append({"id": "c%d" % self.cid, "thread": n, "kind": "close" if close else "reply",
                          "from": frm, "to": list(dict.fromkeys(to)), "title": th["title"], "body": text,
                          "created_at": iso(ts), "url": self._url(n, self.cid)})
        th["replies"] += 1
        th["updated_at"] = iso(ts)
        if close:
            th["state"] = "closed"
            del self.open_threads[n]

    def _seed(self):
        now = utcnow()
        t = now - timedelta(minutes=42)
        plan = [("n", 0), ("r", 0), ("n", 1), ("n", 2), ("r", 2), ("c", 0), ("r", 1), ("n", 3), ("c", 2), ("r", 3)]
        nums = []
        for kind, idx in plan:
            t += timedelta(minutes=self.rnd.uniform(1.5, 5))
            if kind == "n":
                nums.append(self._new_thread(t))
            elif kind == "r":
                self._reply(nums[idx], t)
            else:
                self._reply(nums[idx], t, close=True)
        # make sure ~12 messages exist
        while len(self.msgs) < 12:
            t += timedelta(minutes=2)
            nums.append(self._new_thread(t))
        self.core.set_log(list(self.msgs), dict(self.threads))
        # presence
        for p, host, person, os_name, step in DEMO_MACHINES:
            self.core.presence["%s@%s" % (p, host)] = {
                "v": 1, "pipeline": p, "host": host, "person": person, "os": os_name,
                "status": "working", "step_n": step, "step_text": "", "last_tool": "Edit",
                "last_file": self.rnd.choice(DEMO_FILES[p]), "sessions": 1, "agents": self.rnd.randint(1, 4),
                "updated": iso(now - timedelta(seconds=self.rnd.randint(1, 20))),
            }
        for m in self.core.presence.values():
            self._retext(m)
        self.next_msg_at = time.time() + 3

    # ---- presence
    def _retext(self, m):
        steps = next(p["steps"] for p in self.core.pipelines if p["id"] == m["pipeline"])
        n = m["step_n"]
        if m["status"] == "blocked":
            m["step_text"] = "Blocked: waiting on a reply from another pipeline"
        elif m["status"] == "idle":
            m["step_text"] = "Idle: finished %s, waiting on human" % steps[n - 1]
        else:
            m["step_text"] = ("%s: %s" % (steps[n - 1], self.rnd.choice(DEMO_ACTIVITY)))[:140]

    def _tick_presence(self, now):
        r = self.rnd
        for m in self.core.presence.values():
            steps = next(p["steps"] for p in self.core.pipelines if p["id"] == m["pipeline"])
            upd = parse_ts(m["updated"])
            if r.random() < 0.2 or (now - upd).total_seconds() > 15:
                m["updated"] = iso(now)
                m["last_tool"] = r.choice(DEMO_TOOLS)
                m["last_file"] = r.choice(DEMO_FILES[m["pipeline"]])
                if r.random() < 0.15:
                    m["agents"] = r.randint(1, 4)
                m["sessions"] = min(m["agents"], r.choice([1, 1, 2]))
                if r.random() < 0.12:
                    m["status"] = r.choices(["working", "idle", "blocked"], [8, 2, 1])[0]
                self._retext(m)
            if m["status"] == "working" and r.random() < 0.012 and m["step_n"] < len(steps):
                m["step_n"] += 1
                self._retext(m)

    # ---- main tick (called ~1/s)
    def tick(self):
        now = utcnow()
        t = time.time()
        new = []
        with self.core.lock:
            self._tick_presence(now)
            fired = [p for p in self.pending if p[0] <= t]
            self.pending = [p for p in self.pending if p[0] > t]
            for _, fn in sorted(fired, key=lambda x: x[0]):
                fn(now)
            if t >= self.next_msg_at:
                self.next_msg_at = t + self.rnd.uniform(4, 8)
                if len(self.open_threads) > 8:  # keep things tidy: close the oldest first
                    oldest = min(self.open_threads)
                    self._reply(oldest, now, close=True)
                else:
                    n = self._new_thread(now)
                    if self.rnd.random() < 0.75:
                        self.pending.append((t + self.rnd.uniform(6, 20), lambda nw, n=n: self._reply(n, nw)))
                        if self.rnd.random() < 0.5:
                            self.pending.append((t + self.rnd.uniform(25, 45), lambda nw, n=n: self._reply(n, nw, close=True)))
            new = self.core.set_log(list(self.msgs), dict(self.threads))
            self.core.health["last_poll"] = iso(now)
            self.core.health["rate_remaining"] = 5000
            self.core.publish(new)

    def loop(self):
        while True:
            try:
                self.tick()
            except Exception as e:
                log("demo tick error:", e)
            time.sleep(1)


