class RateLimited(Exception):
    def __init__(self, reset_ts):
        Exception.__init__(self, "rate limited")
        self.reset_ts = reset_ts


class GHError(Exception):
    pass


class GitHub:
    def __init__(self, token, repo):
        self.token = token
        self.repo = repo
        self.etags = {}   # url -> (etag, data)
        self.rate_remaining = None
        self._ctx_extra = None
        self._opener = self._build_opener(None)

    def _build_opener(self, extra_bundle):
        ctx = ssl.create_default_context()
        for var in ("SSL_CERT_FILE", "REQUESTS_CA_BUNDLE", "CURL_CA_BUNDLE"):
            p = os.environ.get(var)
            if p and os.path.isfile(p):
                try:
                    ctx.load_verify_locations(p)
                except Exception:
                    pass
        if extra_bundle and os.path.isfile(extra_bundle):
            try:
                ctx.load_verify_locations(extra_bundle)
            except Exception:
                pass
        return build_opener(ProxyHandler(), HTTPSHandler(context=ctx))

    def _raw(self, url, etag=None, _retry=True):
        headers = {
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
            "User-Agent": "agent-ops-dashboard/1.0",
            "Authorization": "Bearer " + self.token,
        }
        if etag:
            headers["If-None-Match"] = etag
        req = Request(url, headers=headers)
        try:
            resp = self._opener.open(req, timeout=20)
            rem = resp.headers.get("X-RateLimit-Remaining")
            if rem is not None and rem.isdigit():
                self.rate_remaining = int(rem)
            return resp.status, json.loads(resp.read().decode("utf-8") or "null"), resp.headers
        except HTTPError as e:
            rem = e.headers.get("X-RateLimit-Remaining") if e.headers else None
            if rem is not None and rem.isdigit():
                self.rate_remaining = int(rem)
            if e.code == 304:
                return 304, None, e.headers
            msg = ""
            try:
                msg = json.loads(e.read().decode("utf-8")).get("message", "")
            except Exception:
                pass
            if e.code in (403, 429) and (rem == "0" or e.headers.get("Retry-After") or "rate limit" in msg.lower()):
                reset = e.headers.get("X-RateLimit-Reset")
                ra = e.headers.get("Retry-After")
                if ra and ra.isdigit():
                    raise RateLimited(time.time() + int(ra))
                raise RateLimited(int(reset) if reset and reset.isdigit() else time.time() + 60)
            raise GHError("HTTP %d %s" % (e.code, msg[:100]))
        except URLError as e:
            if _retry and ("CERTIFICATE_VERIFY_FAILED" in str(e) or isinstance(getattr(e, "reason", None), ssl.SSLCertVerificationError)):
                if os.path.isfile(FALLBACK_CA):
                    self._opener = self._build_opener(FALLBACK_CA)
                    return self._raw(url, etag, _retry=False)
            raise GHError("network: %s" % (getattr(e, "reason", e),))

    def get_paged(self, path, params="", max_pages=10, use_etag=True):
        """GET a list endpoint. Returns (changed, items). 304 on first page -> (False, cached)."""
        url = "https://api.github.com/repos/%s/%s?%sper_page=100" % (self.repo, path, params + "&" if params else "")
        cached = self.etags.get(url) if use_etag else None
        status, data, hdrs = self._raw(url, cached[0] if cached else None)
        if status == 304 and cached:
            return False, cached[1]
        items = list(data or [])
        pages = 1
        while pages < max_pages:
            m = re.search(r'<([^>]+)>;\s*rel="next"', hdrs.get("Link", "") or "")
            if not m:
                break
            status, data, hdrs = self._raw(m.group(1))
            items.extend(data or [])
            pages += 1
        etag = hdrs.get("ETag") if hdrs else None
        if use_etag and etag:
            self.etags[url] = (etag, items)
        return True, items

    def get_one(self, path):
        _, data, _ = self._raw("https://api.github.com/repos/%s/%s" % (self.repo, path))
        return data


# --------------------------------------------------------------------------- core state + SSE hub
class Core:
    def __init__(self, repo, mode, pipelines_cfg):
        self.lock = threading.RLock()
        self.repo = repo
        self.mode = mode
        self.cfg = pipelines_cfg
        self.pipelines = pipelines_cfg["pipelines"]
        self.ids = [p["id"] for p in self.pipelines]
        self.aliases = pipelines_cfg.get("aliases", {})
        self.messages = []        # full log, oldest first
        self.threads = {}         # number -> thread dict
        self.presence = {}        # key -> raw presence dict
        self.seen_ids = set()
        self.seeded = False
        self.health = {"github": "ok", "rate_remaining": None, "last_poll": None}
        self.subs = []
        self.state_json = "{}"
        self._last_hash = None
        self._last_push = 0.0

    # ---- recipients
    def expand(self, tokens, sender=None):
        out = []
        for tok in tokens:
            tok = norm_token(tok)
            if tok == "ALL":
                cands = list(self.ids)
            elif tok in self.aliases:
                cands = list(self.aliases[tok])
            elif tok in self.ids:
                cands = [tok]
            else:
                cands = []
            for c in cands:
                if c != sender and c not in out:
                    out.append(c)
        return out

    # ---- state building
    def _machines_view(self, now):
        rows = []
        for key, m in self.presence.items():
            upd = parse_ts(m.get("updated"))
            age = int(max(0, (now - upd).total_seconds())) if upd else 10 ** 6
            reported = m.get("status") or "working"
            status = "offline" if age > OFFLINE_S else ("stale" if age > STALE_S else reported)
            rows.append({
                "key": key, "pipeline": m.get("pipeline"), "host": m.get("host"),
                "person": m.get("person", ""), "os": m.get("os", ""),
                "status": status, "reported_status": reported,
                "step_n": m.get("step_n"), "step_text": m.get("step_text", ""),
                "last_tool": m.get("last_tool", ""), "last_file": m.get("last_file", ""),
                "sessions": int(m.get("sessions") or 0), "agents": int(m.get("agents") or 0),
                "updated": m.get("updated"), "age_s": age,
            })
        rows.sort(key=lambda r: (self.ids.index(r["pipeline"]) if r["pipeline"] in self.ids else 99, r["host"] or ""))
        return rows

    def build_state(self):
        now = utcnow()
        machines = self._machines_view(now)
        out_c, in_c = {}, {}
        for m in self.messages:
            out_c[m["from"]] = out_c.get(m["from"], 0) + 1
            for t in m["to"]:
                in_c[t] = in_c.get(t, 0) + 1
        pls = []
        for p in self.pipelines:
            ms = [m for m in machines if m["pipeline"] == p["id"]]
            fresh = [m for m in ms if m["age_s"] <= OFFLINE_S]
            latest = min(ms, key=lambda m: m["age_s"]) if ms else None
            if latest is None:
                status, step_n, step_text, stale = "offline", None, "", False
            elif latest["age_s"] > OFFLINE_S:
                status, step_n, step_text, stale = "offline", latest["step_n"], latest["step_text"], False
            else:
                status, step_n, step_text = latest["reported_status"], latest["step_n"], latest["step_text"]
                stale = latest["age_s"] > STALE_S
            pls.append({
                "id": p["id"], "name": p["name"], "owner": p["owner"], "color": p["color"],
                "steps": p["steps"], "machines": [m["key"] for m in ms],
                "status": status, "stale": stale, "step_n": step_n, "step_text": step_text,
                "agents": sum(m["agents"] for m in fresh),
                "msgs_out": out_c.get(p["id"], 0), "msgs_in": in_c.get(p["id"], 0),
            })
        threads = sorted(self.threads.values(), key=lambda t: t["updated_at"], reverse=True)[:100]
        hour_ago = now - timedelta(hours=1)
        last_hour = sum(1 for m in self.messages if (parse_ts(m["created_at"]) or now) >= hour_ago)
        online = [m for m in machines if m["age_s"] <= OFFLINE_S]
        return {
            "generated_at": iso(now), "mode": self.mode, "repo": self.repo,
            "health": dict(self.health),
            "project": self.cfg.get("project", "Agent Ops"),
            "pipelines": pls, "machines": machines,
            "messages": self.messages[-MAX_MESSAGES:], "threads": threads,
            "stats": {
                "messages_total": len(self.messages), "messages_last_hour": last_hour,
                "open_threads": sum(1 for t in self.threads.values() if t["state"] == "open"),
                "machines_online": len(online), "agents_total": sum(m["agents"] for m in online),
            },
        }

    @staticmethod
    def _norm_hash(state):
        s = dict(state)
        s.pop("generated_at", None)
        h = dict(s["health"]); h.pop("last_poll", None); h.pop("rate_remaining", None)
        s["health"] = h
        s["machines"] = [{k: v for k, v in m.items() if k != "age_s"} for m in s["machines"]]
        return json.dumps(s, sort_keys=True, separators=(",", ":"))

    # ---- SSE hub
    @staticmethod
    def _sse(event, payload):
        return "event: %s\ndata: %s\n\n" % (event, payload)

    def _broadcast(self, text):
        dead = []
        for q in self.subs:
            try:
                q.put_nowait(text)
            except queue.Full:
                dead.append(q)
        for q in dead:
            self.subs.remove(q)

    def subscribe(self):
        q = queue.Queue(maxsize=2000)
        with self.lock:
            q.put(self._sse("state", json.dumps(self.build_state(), separators=(",", ":"))))
            self.subs.append(q)
        return q

    def unsubscribe(self, q):
        with self.lock:
            if q in self.subs:
                self.subs.remove(q)

    def publish(self, new_messages=(), force=False):
        """Rebuild state; push new messages (in order), then state when changed (or every 30 s)."""
        with self.lock:
            for m in new_messages:
                self._broadcast(self._sse("message", json.dumps(m, separators=(",", ":"))))
            st = self.build_state()
            self.state_json = json.dumps(st, separators=(",", ":"))
            h = self._norm_hash(st)
            now = time.time()
            if force or h != self._last_hash or now - self._last_push > 30:
                self._last_hash = h
                self._last_push = now
                self._broadcast(self._sse("state", self.state_json))

    def current_state_json(self):
        with self.lock:
            return json.dumps(self.build_state(), separators=(",", ":"))

    def set_log(self, messages, threads):
        """Replace the message log; returns list of NEW messages (empty on first seeding)."""
        with self.lock:
            messages = sorted(messages, key=lambda m: (m["created_at"], m["id"]))
            new = [m for m in messages if m["id"] not in self.seen_ids]
            self.seen_ids.update(m["id"] for m in messages)
            self.messages = messages
            self.threads = threads
            if not self.seeded:
                self.seeded = True
                return []
            return new


