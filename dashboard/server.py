class LiveCollector:
    def __init__(self, core, gh, interval):
        self.core, self.gh, self.interval = core, gh, interval
        self.issues = {}       # number -> issue json (non-PR)
        self.pr_numbers = set()
        self.comments = {}     # id -> comment json (with _issue number)
        self.since = None
        self.presence_issue = None
        self.presence_checked = 0.0
        self.last_full_comments = 0.0
        self.backoff_until = 0.0
        self.first = True

    def loop(self):
        while True:
            try:
                self.poll()
            except Exception as e:  # never die
                self.core.health["github"] = "error: %s" % str(e)[:120]
                try:
                    self.core.publish()
                except Exception:
                    pass
            time.sleep(self.interval)

    def poll(self):
        core, gh = self.core, self.gh
        if time.time() < self.backoff_until:
            return
        err = None
        issues_changed = False
        try:
            changed, items = gh.get_paged("issues", "state=all&sort=updated&direction=desc", max_pages=5)
            if changed or self.first:
                issues_changed = True
                for it in items:
                    if "pull_request" in it:
                        self.pr_numbers.add(it["number"])
                    else:
                        self.issues[it["number"]] = it
            pres = next((i for i in self.issues.values()
                         if i.get("state") == "open" and any(l.get("name") == "presence" for l in i.get("labels", []))), None)
            if pres:
                self.presence_issue = pres["number"]
            elif time.time() - self.presence_checked > 30:
                self.presence_checked = time.time()
                _, found = gh.get_paged("issues", "labels=presence&state=open", max_pages=1)
                found = [i for i in found if "pull_request" not in i]
                self.presence_issue = found[0]["number"] if found else None
                for i in found:
                    self.issues[i["number"]] = i
        except RateLimited as e:
            self._rate_limited(e)
            return
        except Exception as e:
            err = "issues: %s" % e
        try:
            if issues_changed or self.first or time.time() - self.last_full_comments > 60:
                self.last_full_comments = time.time()
                params = "sort=updated&direction=asc" + ("&since=" + self.since if self.since else "")
                changed, items = gh.get_paged("issues/comments", params, max_pages=30)
                if changed:
                    for c in items:
                        n = self._issue_no(c)
                        if n is None:
                            continue
                        c["_issue"] = n
                        self.comments[c["id"]] = c
                        if self.since is None or c["updated_at"] > self.since:
                            self.since = c["updated_at"]
        except RateLimited as e:
            self._rate_limited(e)
            return
        except Exception as e:
            err = err or "comments: %s" % e
        try:
            if self.presence_issue:
                changed, items = gh.get_paged("issues/%d/comments" % self.presence_issue, max_pages=5)
                if changed or self.first:
                    self._parse_presence(items)
            else:
                with core.lock:
                    core.presence = {}
        except RateLimited as e:
            self._rate_limited(e)
            return
        except Exception as e:
            err = err or "presence: %s" % e
        self.first = False
        core.health["github"] = ("error: " + err[:120]) if err else "ok"
        core.health["rate_remaining"] = gh.rate_remaining
        core.health["last_poll"] = iso(utcnow())
        msgs, threads = self._build_log()
        new = core.set_log(msgs, threads)
        core.publish(new)

    def _rate_limited(self, e):
        wait = max(5, min(int(e.reset_ts - time.time()) + 2, 900))
        self.backoff_until = time.time() + wait
        self.core.health["github"] = "error: rate limited, retry in %ds" % wait
        self.core.health["rate_remaining"] = 0
        self.core.health["last_poll"] = iso(utcnow())
        self.core.publish()

    def _issue_no(self, c):
        m = re.search(r"/issues/(\d+)$", c.get("issue_url", ""))
        if not m:
            return None
        n = int(m.group(1))
        if n in self.issues:
            return n
        if n in self.pr_numbers:
            return None
        try:  # issue older than the list window: look it up once
            it = self.gh.get_one("issues/%d" % n)
            if "pull_request" in it:
                self.pr_numbers.add(n)
                return None
            self.issues[n] = it
            return n
        except Exception:
            return None

    def _parse_presence(self, items):
        out = {}
        for c in items:
            body = c.get("body") or ""
            m = re.search(r"```json\s*(\{.*?\})\s*```", body, re.S)
            if not m:
                continue
            try:
                d = json.loads(m.group(1))
            except Exception:
                continue
            mk = re.search(r"<!--\s*presence:([^:\s]+):([^\s>]+)\s*-->", body)
            pipe = d.get("pipeline") or (mk.group(1) if mk else None)
            host = d.get("host") or (mk.group(2) if mk else None)
            if not pipe or not host:
                continue
            d["pipeline"], d["host"] = pipe, host
            if not parse_ts(d.get("updated")):
                d["updated"] = c.get("updated_at")
            key = "%s@%s" % (pipe, host)
            prev = out.get(key)
            if not prev or (parse_ts(d["updated"]) or 0) >= (parse_ts(prev["updated"]) or 0):
                out[key] = d
        with self.core.lock:
            self.core.presence = out

    def _build_log(self):
        core = self.core
        msgs, threads = [], {}
        by_issue = {}
        for c in self.comments.values():
            by_issue.setdefault(c["_issue"], []).append(c)
        for n, it in self.issues.items():
            labels = [l.get("name", "") for l in it.get("labels", [])]
            if "presence" in labels:
                continue
            title_raw = it.get("title") or ""
            tm = TITLE_RE.match(title_raw)
            from_lbl = [l[5:] for l in labels if l.startswith("from:")]
            to_lbl = [norm_token(l[3:]) for l in labels if l.startswith("to:")]
            if not tm and not from_lbl:
                continue  # not a comms thread
            title = tm.group(3).strip() if tm else title_raw
            sender = norm_token(from_lbl[0]) if from_lbl else norm_token(tm.group(1))
            if sender == "P4":
                sender = "P4a"
            to_tokens = to_lbl or ([norm_token(tm.group(2))] if tm else [])
            raw_body = it.get("body") or ""
            cms = sorted(by_issue.get(n, []), key=lambda c: (c["created_at"], c["id"]))
            threads[n] = {
                "number": n, "title": title, "state": it.get("state", "open"),
                "from": sender, "to": to_tokens, "replies": len(cms),
                "updated_at": it.get("updated_at"), "url": it.get("html_url"),
            }
            msgs.append({
                "id": "i%d" % n, "thread": n, "kind": "thread", "from": sender,
                "to": core.expand(to_tokens, sender), "title": title,
                "body": clean_body(raw_body)[:400], "created_at": it["created_at"], "url": it.get("html_url"),
            })
            recips_base = core.expand(to_tokens)
            for c in cms:
                cb = c.get("body") or ""
                sm = SIG_RE.search(cb)
                if sm:
                    rs = sm.group(1)
                    rs = "P4a" if rs == "P4" else rs
                else:  # unsigned (human comment): assume the addressee answered
                    rs = recips_base[0] if recips_base else sender
                to = [p for p in recips_base + [sender] if p != rs]
                to = list(dict.fromkeys(to))
                cleaned = clean_body(cb)
                kind = "reply"
                if re.match(r"\s*Resolved:", cleaned, re.I):
                    kind = "close"
                    cleaned = re.sub(r"^\s*Resolved:\s*", "", cleaned, flags=re.I)
                msgs.append({
                    "id": "c%d" % c["id"], "thread": n, "kind": kind, "from": rs, "to": to,
                    "title": title, "body": cleaned[:400], "created_at": c["created_at"],
                    "url": c.get("html_url"),
                })
        return msgs, threads


