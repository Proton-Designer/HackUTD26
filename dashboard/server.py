def content_type(path):
    ext = os.path.splitext(path)[1].lower()
    if ext in CT:
        return CT[ext]
    return mimetypes.guess_type(path)[0] or "application/octet-stream"


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"
    server_version = "AgentOps/1.0"

    def log_message(self, fmt, *args):
        pass

    def _send(self, code, body, ctype="text/plain; charset=utf-8", head=False):
        if isinstance(body, str):
            body = body.encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("Access-Control-Allow-Origin", "*")
        self.end_headers()
        if not head:
            self.wfile.write(body)

    def do_HEAD(self):
        self._route(head=True)

    def do_GET(self):
        self._route()

    def _route(self, head=False):
        try:
            path = unquote(urlparse(self.path).path)
            if path in ("/", "/index.html"):
                return self._file(os.path.join(PUBLIC_DIR, "index.html"), head)
            if path.startswith("/static/"):
                rel = path[len("/static/"):]
                full = os.path.realpath(os.path.join(PUBLIC_DIR, rel.replace("\\", "/")))
                root = os.path.realpath(PUBLIC_DIR)
                if "\x00" in rel or not (full == root or full.startswith(root + os.sep)):
                    return self._send(403, "forbidden", head=head)
                return self._file(full, head)
            if path == "/api/state":
                return self._send(200, CORE.current_state_json(), "application/json; charset=utf-8", head)
            if path == "/api/events":
                return self._events()
            if path == "/favicon.ico":
                return self._send(204, b"", head=head)
            self._send(404, "not found", head=head)
        except (OSError, ConnectionError):
            self.close_connection = True
        except Exception as e:
            try:
                self._send(500, "server error: %s" % e)
            except Exception:
                self.close_connection = True

    def _file(self, full, head):
        if not os.path.isfile(full):
            if full.endswith("index.html"):
                return self._send(404, "public/index.html not built yet. API is live at /api/state and /api/events.", head=head)
            return self._send(404, "not found", head=head)
        with open(full, "rb") as f:
            data = f.read()
        self._send(200, data, content_type(full), head)

    def _events(self):
        q = CORE.subscribe()
        try:
            self.send_response(200)
            self.send_header("Content-Type", "text/event-stream; charset=utf-8")
            self.send_header("Cache-Control", "no-store")
            self.send_header("Connection", "close")
            self.send_header("X-Accel-Buffering", "no")
            self.send_header("Access-Control-Allow-Origin", "*")
            self.end_headers()
            self.wfile.write(b"retry: 3000\n\n")
            self.wfile.flush()
            while True:
                try:
                    item = q.get(timeout=15)
                    self.wfile.write(item.encode("utf-8"))
                except queue.Empty:
                    self.wfile.write(b": ping\n\n")
                self.wfile.flush()
        except (OSError, ConnectionError, ValueError):
            pass
        finally:
            CORE.unsubscribe(q)
            self.close_connection = True


class Server(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True
    request_queue_size = 64

    def handle_error(self, request, client_address):
        if isinstance(sys.exc_info()[1], (OSError, ConnectionError)):
            return  # client went away
        ThreadingHTTPServer.handle_error(self, request, client_address)


